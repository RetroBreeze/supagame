set local realtime.topic = 'unrelated-topic';
select is((select count(*) from realtime.messages where topic='supagame:leaderboard:live-test'),0::bigint,'unrelated channel is not authorized');
reset role;
delete from game_players where user_id='90000000-0000-4000-8000-000000000001';
select is((select count(*) from live_test_messages),5::bigint,'deletion invalidates before cascading scores disappear');
select * from finish();
