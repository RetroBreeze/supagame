begin;
create extension if not exists pgtap with schema extensions;
set local search_path = public, extensions;
select no_plan();
select has_function('sg_private', 'live_invalidate', array[]::text[]);
create temporary view live_test_messages as select payload - 'id' as payload, event, topic, private from realtime.messages where topic='supagame:leaderboard:live-test';
insert into auth.users(id) values ('90000000-0000-4000-8000-000000000001');
insert into public.game_players(user_id,display_name) values ('90000000-0000-4000-8000-000000000001','Live player');
insert into public.game_leaderboards(id,kind,sort_direction) values ('live-test','points','desc');
set local role authenticated;
set local request.jwt.claims = '{"sub":"90000000-0000-4000-8000-000000000001","role":"authenticated"}';
select public.sg_submit_score('live-test',10,'90000000-0000-4000-8000-000000000002');
select public.sg_submit_score('live-test',9,'90000000-0000-4000-8000-000000000003');
select public.sg_submit_score('live-test',10,'90000000-0000-4000-8000-000000000004');
reset role;
select is((select count(*) from live_test_messages),1::bigint,'non-best/equal submissions do not emit');
select is((select payload from live_test_messages limit 1),'{"boardId":"live-test"}'::jsonb,'payload contains only board identifier');
select ok((select bool_and(private and event='changed' and topic='supagame:leaderboard:live-test') from live_test_messages),'private board-scoped messages');
update game_players set display_name='New name';
select is((select count(*) from live_test_messages),2::bigint,'name changes invalidate');
update game_players set hidden=true;
select is((select count(*) from live_test_messages),3::bigint,'hiding invalidates');
update game_players set display_name='Private name';
select is((select count(*) from live_test_messages),3::bigint,'hidden name does not invalidate');
update game_players set hidden=false;
select is((select count(*) from live_test_messages),4::bigint,'unhiding invalidates');
update game_leaderboards set min_value=0 where id='live-test';
select is((select min_value from game_leaderboards where id='live-test'),0::bigint,'unrelated board changes are not suppressed');
select is((select count(*) from live_test_messages),4::bigint,'bounds changes do not invalidate ranks');
select ok(not has_function_privilege('authenticated','sg_private.live_invalidate()','execute'),'client cannot execute trigger');
select ok((select prosecdef and proconfig @> array['search_path=""'] from pg_proc where oid='sg_private.live_invalidate()'::regprocedure),'definer search path fixed');
select ok(exists(select 1 from pg_policies where schemaname='realtime' and policyname='supagame_live_no_client_send' and permissive='RESTRICTIVE' and cmd='INSERT'),'client sending is restricted');
